// Generate the icon-name union from assets/icons/. Startup and deferred glyphs share one
// namespace, so basenames must be unique across both directories.
// Run manually with npm run gen:icon-names.

import { globSync, writeFileSync } from 'node:fs';
import { fail } from '../lib/proc.mjs';

const OUT = 'tools/icons/lib/icon-names.d.ts';

const names = globSync('assets/icons/**/*.svg')
  .map((path) =>
    path
      .split('/')
      .pop()
      .replace(/\.svg$/, '')
  )
  .sort();

if (names.length === 0)
  fail('No SVGs found under assets/icons/ — refusing to write an empty union.');

const duplicates = names.filter((name, index) => names.indexOf(name) !== index);
if (duplicates.length)
  fail(
    `Icon basenames must be unique across assets/icons/ and deferred/: ${duplicates.join(', ')}`
  );

const union = names.map((name) => `  | '${name}'`).join('\n');
const contents = `// AUTO-GENERATED by tools/icons/gen-icon-names.mjs — do not edit by hand.
// Run \`node tools/icons/gen-icon-names.mjs\` to regenerate.
export type IconName =
${union};
`;

writeFileSync(OUT, contents);
console.log(`Wrote ${names.length} icon names to ${OUT}`);

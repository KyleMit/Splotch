// Generate a TypeScript union of icon names from the SVGs in src/lib/icons/ —
// the startup set at the top level plus the lazily registered set in deferred/
// (ADR-0164) — so <Icon name="…"> gets editor autocomplete + typo checking
// (see Icon.svelte). Basenames must be unique across both directories: the
// union, the registry, and `data-icon` all key on the bare name.
// Runs automatically via the prebuild npm hooks; run manually with:
//   node tools/icons/gen-icon-names.mjs

import { globSync, readFileSync, writeFileSync } from 'node:fs';
import { fail } from '../lib/proc.mjs';
import { isSpot } from './lib/icon-chroma.mjs';

const OUT = 'web/src/lib/components/icon-names.d.ts';
const META_OUT = 'web/src/lib/components/icon-meta.ts';
const ICON_TYPES = 'web/src/lib/components/iconTypes.ts';

const files = globSync('web/src/lib/icons/**/*.svg').sort();
const nameOf = (path) =>
  path
    .split('/')
    .pop()
    .replace(/\.svg$/, '');
const names = files.map(nameOf).sort();

if (names.length === 0)
  fail('No SVGs found under web/src/lib/icons/ — refusing to write an empty union.');

const duplicates = names.filter((name, index) => names.indexOf(name) !== index);
if (duplicates.length)
  fail(
    `Icon basenames must be unique across web/src/lib/icons/ and deferred/: ${duplicates.join(', ')}`
  );

const union = names.map((name) => `  | '${name}'`).join('\n');
const contents = `// AUTO-GENERATED by tools/icons/gen-icon-names.mjs — do not edit by hand.
// Run \`node tools/icons/gen-icon-names.mjs\` (or any dev/build) to regenerate.
export type IconName =
${union};
`;

writeFileSync(OUT, contents);
console.log(`Wrote ${names.length} icon names to ${OUT}`);

// The colorful ("spot") subset, classified from the painted hues so Icon.svelte's
// opt-out set never needs a hand edit for a new spot SVG. NON_RENDERABLE_ICONS is
// read from its owning module's source: this script must run on the engines
// floor, where importing a .ts module still needs a flag.
const nonRenderable = readFileSync(ICON_TYPES, 'utf8').match(
  /NON_RENDERABLE_ICONS = \[([^\]]*)\] as const/
)?.[1];
if (nonRenderable === undefined) fail(`Could not find NON_RENDERABLE_ICONS in ${ICON_TYPES}`);
const excluded = new Set([...nonRenderable.matchAll(/'([^']+)'/g)].map((m) => m[1]));
const colorful = files
  .filter((path) => !excluded.has(nameOf(path)) && isSpot(readFileSync(path, 'utf8')))
  .map(nameOf)
  .sort();
const metaContents = `// AUTO-GENERATED by tools/icons/gen-icon-names.mjs — do not edit by hand.
// Every renderable icon whose SVG paints a saturated hue (tools/icons/lib/icon-chroma.mjs).
// Icon.svelte.test.ts fails when this list is stale; rerun \`npm run gen:icon-names\`.
export const COLORFUL_ICONS = [
${colorful.map((name) => `  '${name}',`).join('\n')}
] as const;
`;
writeFileSync(META_OUT, metaContents);
console.log(`Wrote ${colorful.length} colorful icon names to ${META_OUT}`);

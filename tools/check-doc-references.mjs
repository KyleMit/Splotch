// `readFirstLine` is deferred so only candidate docs are read: the tree holds
// megabytes of evidence JSON that reading up front would cost seconds.
export function isScannedDoc(file, readFirstLine = () => '') {
  if (!DOC_EXTENSIONS.some((ext) => file.endsWith(ext))) return false;
  if (HISTORY_PREFIXES.some((prefix) => file.startsWith(prefix))) return false;
  if (HISTORY_FILE.test(file)) return false;
  const isDirect = DIRECT_PROVIDER_PATHS.some((path) => file.startsWith(`${path}/`));
  if (!isDirect && GENERATED_COPY_PREFIXES.some((prefix) => file.startsWith(prefix))) return false;
  return !GENERATED_MARKER.test(readFirstLine());
}

// Blanks fenced blocks, keeping their line breaks, so path and identifier
// extraction never reads shell or code while line numbers still match the
// source; npm targets are read from the full text.
export function proseOnly(text) {
  let inFence = false;
  return text
    .split('\n')
    .map((line) => {
      if (FENCE.test(line)) {
        inFence = !inFence;
        return '';
      }
      return inFence ? '' : line;
    })
    .join('\n');
}

function lineStarts(text) {
  const starts = [0];
  for (let i = 0; i < text.length; i += 1) if (text.charCodeAt(i) === 10) starts.push(i + 1);
  return starts;
}

function lineOf(starts, index) {
  let low = 0;
  let high = starts.length - 1;
  while (low < high) {
    const mid = (low + high + 1) >> 1;
    if (starts[mid] <= index) low = mid;
    else high = mid - 1;
  }
  return low + 1;
}

// A span is read as a repo path only when it has at least two segments and is
// anchored somewhere this repo is: it opens with `./`/`../`, its first segment
// is a top-level folder (of the repo or of `web/`), or it names a file under a
// folder name the tree has. A single filename (`findings.json`) names a runtime
// artifact as often as a tracked file; an extensionless span under some inner
// folder name is as often a GitHub action (`actions/checkout`), a branch, a
// lint rule, or a coloring page id; and a path on another machine
// (`Library/Preferences/…`, a capture folder's `packet/diff.patch`) starts
// somewhere the repo does not.
export function pathCandidate(raw, { topLevelNames, dirNames }) {
  const text = raw.trim().replace(LINE_SUFFIX, '').replace(/\/$/, '');
  if (!text || NOT_A_CONCRETE_PATH.test(text) || PLACEHOLDER.test(text)) return null;
  const segments = text.split('/');
  if (segments.length < 2 || !segments.every((segment) => PATH_SEGMENT.test(segment))) return null;
  if (segments.every((segment) => NAVIGATION_SEGMENT.test(segment))) return null;
  if (NAVIGATION_SEGMENT.test(segments[0]) || topLevelNames.has(segments[0])) return text;
  return HAS_EXTENSION.test(text) && dirNames.has(segments[0]) ? text : null;
}

// A Markdown link target is an explicit file reference, so a single filename
// counts and nothing about its shape has to vouch for it.
export function linkTarget(raw) {
  const target = raw.replace(/[?#].*$/, '');
  if (!target || URL_SCHEME.test(target) || target.startsWith('/')) return null;
  let decoded;
  try {
    decoded = decodeURI(target);
  } catch {
    return null;
  }
  if (/[<>{}*]|…|\.\.\./.test(decoded) || PLACEHOLDER.test(decoded)) return null;
  return decoded.replace(/\/$/, '');
}

export function extractReferences(text, { topLevelNames, dirNames, identifiers = false }) {
  const refs = [];
  const prose = proseOnly(text);
  const starts = lineStarts(text);
  const proseStarts = lineStarts(prose);

  for (const match of prose.matchAll(INLINE_CODE)) {
    const span = match[1];
    const line = lineOf(proseStarts, match.index);
    const path = pathCandidate(span, { topLevelNames, dirNames });
    if (path) {
      refs.push({ kind: 'path', ref: path, line });
      continue;
    }
    if (!identifiers) continue;
    const identifier = span.trim().match(IDENTIFIER_SPAN);
    if (identifier) refs.push({ kind: 'identifier', ref: identifier[1], line });
  }

  // Link syntax quoted inside a code span (`![](url)`) is an example, not a link.
  const linkText = prose.replace(INLINE_CODE, (span) => ' '.repeat(span.length));
  for (const match of linkText.matchAll(MARKDOWN_LINK)) {
    const target = linkTarget(match[1]);
    if (target) refs.push({ kind: 'link', ref: target, line: lineOf(proseStarts, match.index) });
  }

  for (const match of text.matchAll(NPM_RUN)) {
    const name = match[1];
    // `npm run perf:*` names a namespace; the glob is cut off by the match.
    if (name.endsWith(':')) continue;
    refs.push({ kind: 'script', ref: name, line: lineOf(starts, match.index) });
  }
  return refs;
}

// Where a reader follows a link from: beside the doc, except for a Ruler
// orientation source, whose text renders in the CLAUDE.md/AGENTS.md generated
// next to its `.ruler/` folder. Skill sources keep their own folder, since the
// generated skill copies sit at the same depth.
function linkBase(file) {
  const dir = posix.dirname(file);
  if (file.startsWith('.ruler/skills/')) return dir;
  if (dir === '.ruler') return '';
  if (dir.endsWith('/.ruler')) return posix.dirname(dir);
  return dir;
}

function linkPath(file, ref) {
  return posix.normalize(posix.join(linkBase(file), ref));
}

// A doc resolves a relative path in prose against its own folder or any folder above
// it: skills write paths relative to their package, nested orientation docs
// relative to their area, and most docs relative to the repo root.
function candidatePaths(file, ref) {
  const paths = [];
  let dir = posix.dirname(file);
  while (dir !== '.') {
    paths.push(posix.normalize(posix.join(dir, ref)));
    dir = posix.dirname(dir);
  }
  paths.push(posix.normalize(ref));
  return paths;
}

const AMBIGUOUS_TAIL = Symbol('ambiguous tail');

export function createIndex({
  files,
  packages,
  ignoredPaths = new Set(),
  sourceWords = new Set(),
}) {
  const tracked = new Set(files);
  const dirs = new Set();
  const dirNames = new Set();
  const topLevelNames = new Set();
  // Every in-tree tail of two or more segments, mapped to the one path it
  // ends, so a doc may name a file by the end of its path
  // (`lib/drawing/engine.ts`, written from a doc about web/src) the way the
  // prose around it does. A tail two paths share (`docs/pipeline.md`) names
  // neither, since either could vanish while the reference kept passing.
  const tails = new Map();
  for (const file of files) {
    const segments = file.split('/');
    for (let start = 1; start < segments.length - 1; start += 1) {
      for (let end = start + 2; end <= segments.length; end += 1) {
        const tail = segments.slice(start, end).join('/');
        const owner = segments.slice(0, end).join('/');
        const known = tails.get(tail);
        tails.set(tail, known === undefined || known === owner ? owner : AMBIGUOUS_TAIL);
      }
    }
    topLevelNames.add(segments[0]);
    if (segments[0] === 'web' && segments.length > 2) topLevelNames.add(segments[1]);
    segments.slice(0, -1).forEach((segment, i) => {
      dirNames.add(segment);
      dirs.add(segments.slice(0, i + 1).join('/'));
    });
  }
  return { tracked, dirs, dirNames, topLevelNames, tails, packages, ignoredPaths, sourceWords };
}

// A doc inside a package with its own scripts (tools/asset-gen) may name those
// aliases as well as the root scripts.
function scriptScopes(file, packages) {
  return [...packages.keys()].filter((dir) => dir === '' || file.startsWith(`${dir}/`));
}

export function resolveReference(file, { kind, ref }, index) {
  if (kind === 'script') {
    const found = scriptScopes(file, index.packages).some((dir) =>
      index.packages.get(dir).has(ref)
    );
    return found ? 'resolved' : 'missing';
  }
  if (kind === 'identifier') return index.sourceWords.has(ref) ? 'resolved' : 'missing';
  if (kind === 'link') {
    const path = linkPath(file, ref);
    if (index.tracked.has(path) || index.dirs.has(path)) return 'resolved';
    return index.ignoredPaths.has(path) ? 'ignored' : 'missing';
  }
  const candidates = candidatePaths(file, ref);
  if (candidates.some((path) => index.tracked.has(path) || index.dirs.has(path))) return 'resolved';
  const tailOwner = index.tails.get(ref);
  if (!NAVIGATION_SEGMENT.test(ref.split('/')[0]) && typeof tailOwner === 'string') {
    return 'resolved';
  }
  if (candidates.some((path) => index.ignoredPaths.has(path))) return 'ignored';
  return 'missing';
}

function isAllowed(file, ref) {
  return ALLOWED_REFERENCES.some((entry) => entry.doc === file && entry.ref === ref);
}

export function findUnresolved({ docs, read, index, identifiers = false }) {
  const findings = [];
  for (const file of docs) {
    for (const reference of extractReferences(read(file), { ...index, identifiers })) {
      if (resolveReference(file, reference, index) !== 'missing') continue;
      if (isAllowed(file, reference.ref)) continue;
      findings.push({ file, line: reference.line, kind: reference.kind, ref: reference.ref });
    }
  }
  return findings;
}

// An allowlist entry that no longer matches anything is itself drift: the doc
// was fixed or reworded and the exemption would hide the next real miss.
export function staleAllowances({ docs, read, index }) {
  const live = new Set();
  for (const file of docs) {
    for (const reference of extractReferences(read(file), index)) {
      if (resolveReference(file, reference, index) === 'missing') {
        live.add(`${file}\0${reference.ref}`);
      }
    }
  }
  return ALLOWED_REFERENCES.filter(({ doc, ref }) => !live.has(`${doc}\0${ref}`));
}

function trackedFiles(root) {
  return capture('git', ['ls-files', '-z'], { cwd: root }).split('\0').filter(Boolean);
}

function readPackages(root, files) {
  const packages = new Map();
  for (const file of files) {
    if (posix.basename(file) !== 'package.json') continue;
    const dir = posix.dirname(file) === '.' ? '' : posix.dirname(file);
    const { scripts = {} } = JSON.parse(readFileSync(join(root, file), 'utf8'));
    packages.set(dir, new Set(Object.keys(scripts)));
  }
  return packages;
}

function readSourceWords(root, files) {
  const words = new Set();
  for (const file of files) {
    if (!IDENTIFIER_SOURCE_EXTENSIONS.test(file) || file.startsWith('perf-profiles/')) continue;
    for (const [word] of readFileSync(join(root, file), 'utf8').matchAll(WORD)) words.add(word);
  }
  return words;
}

// A directory-only pattern (`build/`) matches a nonexistent path only through
// a child, since git cannot know the bare name would be a directory.
const DIRECTORY_PROBE = '.probe';

// Build outputs and local-only files (`web/build/`, `web/.env.local`) are
// named in docs on purpose and never tracked; the repo's own ignore rules are
// the authority on which paths those are. Only a pattern from a tracked
// .gitignore counts: a developer's global excludes or `.git/info/exclude`
// would otherwise pass a path locally that fails in CI.
function ignoredAmong(root, paths, tracked) {
  if (!paths.length) return new Set();
  const result = spawnSync('git', ['check-ignore', '--no-index', '--stdin', '-z', '-v'], {
    cwd: root,
    input: paths.flatMap((path) => [path, `${path}/${DIRECTORY_PROBE}`]).join('\0'),
    encoding: 'utf8',
  });
  if (result.status !== 0 && result.status !== 1) {
    throw new Error(`git check-ignore failed: ${result.stderr}`);
  }
  return ignoredByTrackedRules(result.stdout, tracked);
}

// Parses `git check-ignore -v -z` records (source, line, pattern, path). A
// negated pattern is reported as the last match too, and un-ignores its path.
export function ignoredByTrackedRules(output, tracked) {
  const fields = output.split('\0');
  const ignored = new Set();
  for (let i = 0; i + 3 < fields.length; i += 4) {
    const [source, , pattern, path] = fields.slice(i, i + 4);
    if (!tracked.has(source) || posix.basename(source) !== '.gitignore') continue;
    if (pattern.startsWith('!')) continue;
    ignored.add(path.replace(`/${DIRECTORY_PROBE}`, ''));
  }
  return ignored;
}

export function scan({ root = ROOT, identifiers = false } = {}) {
  const files = trackedFiles(root);
  const cache = new Map();
  const read = (file) => {
    if (!cache.has(file)) cache.set(file, readFileSync(join(root, file), 'utf8'));
    return cache.get(file);
  };
  const docs = files.filter((file) => isScannedDoc(file, () => read(file).split('\n', 1)[0]));
  const index = createIndex({
    files,
    packages: readPackages(root, files),
    sourceWords: identifiers ? readSourceWords(root, files) : new Set(),
  });

  const unresolvedPaths = new Set();
  for (const file of docs) {
    for (const reference of extractReferences(read(file), index)) {
      if (reference.kind === 'script' || reference.kind === 'identifier') continue;
      if (resolveReference(file, reference, index) !== 'missing') continue;
      const paths =
        reference.kind === 'link'
          ? [linkPath(file, reference.ref)]
          : candidatePaths(file, reference.ref);
      for (const path of paths) {
        if (!path.startsWith('..')) unresolvedPaths.add(path);
      }
    }
  }
  index.ignoredPaths = ignoredAmong(root, [...unresolvedPaths], index.tracked);
  return {
    findings: findUnresolved({ docs, read, index, identifiers }),
    stale: staleAllowances({ docs, read, index }),
  };
}

const KIND_LABELS = {
  path: 'path',
  link: 'link',
  script: 'npm script',
  identifier: 'identifier',
};

export function report({ findings, stale }, log = console) {
  const gating = findings.filter(({ kind }) => kind !== 'identifier');
  const advisory = findings.filter(({ kind }) => kind === 'identifier');

  if (advisory.length) {
    log.log(`Identifiers no tracked source file names (advisory, ${advisory.length}):\n`);
    for (const { file, line, ref } of advisory) log.log(`  ${file}:${line}  ${ref}`);
    log.log('');
  }
  for (const { doc, ref } of stale) {
    log.error(`✗ ALLOWED_REFERENCES entry matches nothing: ${doc} → ${ref}`);
  }
  if (!gating.length && !stale.length) {
    log.log('✓ Doc references: every repo path and npm script resolves');
    return 0;
  }
  if (gating.length) {
    log.error(`✗ Doc references: ${gating.length} unresolved reference(s)\n`);
    for (const { file, line, kind, ref } of gating) {
      log.error(`  ${file}:${line}  ${KIND_LABELS[kind]} ${ref}`);
    }
    log.error(
      '\nUpdate each reference to what it now names, or delete it if the thing is gone.' +
        '\nA reference that must stay unresolvable goes in ALLOWED_REFERENCES with its reason.'
    );
  }
  return 1;
}

export function main(argv = process.argv.slice(2)) {
  const { values } = parseArgs({
    args: argv,
    options: { json: { type: 'boolean' }, identifiers: { type: 'boolean' } },
  });
  const result = scan({ identifiers: values.identifiers });
  if (values.json) {
    console.log(JSON.stringify(result, null, 2));
    return result.findings.some(({ kind }) => kind !== 'identifier') || result.stale.length ? 1 : 0;
  }
  return report(result);
}

if (isMain(import.meta.url)) {
  runMain(async () => {
    process.exitCode = main();
  });
}

// Reports references in living docs, skills, and rules that no longer resolve:
// repo paths and `npm run` targets. A renamed file or deleted script leaves
// every doc that mentioned it quietly wrong, and nothing else in the toolchain
// reads prose (issue #2325).
//
//   node tools/check-doc-references.mjs                report unresolved references, exit 1 on any
//   node tools/check-doc-references.mjs --json         machine-readable findings
//   node tools/check-doc-references.mjs --identifiers  also list code identifiers no source file names
//
// Identifiers are advisory and never fail the run: most identifier-shaped code
// spans in these docs name a platform API, an env var, a JSON field, or a tool
// of another program, which no repo search can tell apart from a stale symbol.
// The reconcile-docs-with-code skill reads that list with judgment.
//
// Deterministic by construction: it resolves against `git ls-files` and the
// tracked package.json files, never the working tree, so an untracked local
// file cannot mask a stale reference and a fresh CI checkout agrees with a
// developer's machine.


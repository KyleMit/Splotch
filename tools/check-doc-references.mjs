const PLACEHOLDER = /NNNN|XXXX|YYYY|[-_]N\./;
const PATH_SEGMENT = /^[\w.@+-]+$/;
const NAVIGATION_SEGMENT = /^\.\.?$/;
const HAS_EXTENSION = /[^/.]\.\w+$/;
const LINE_SUFFIX = /(:\d+(-\d+)?|#L\d+(-L?\d+)?)$/;

const NPM_RUN = /\bnpm run (?:--?[\w-]+ )*([\w:.-]+)/g;
const INLINE_CODE = /(?<!`)`([^`\n]+)`(?!`)/g;
const MARKDOWN_LINK = /\]\(([^)\s]+)(?:\s+"[^"]*")?\)/g;
const FENCE = /^\s*(```|~~~)/;
const URL_SCHEME = /^[a-z][a-z+.-]*:/i;

// Identifier-shaped spans worth checking: a call (`createFoo()`), camelCase or
// PascalCase with an inner capital, or SCREAMING_SNAKE. A lone lowercase word
// is far more often an English noun, CSS keyword, or JSON field than a symbol.
const IDENTIFIER_SPAN =
  /^(?:[A-Za-z_$][\w$]*\.)*([a-z_$][\w$]*[A-Z][\w$]*|[A-Z][a-z0-9]+[A-Z][\w$]*|[A-Z][A-Z0-9]*_[A-Z0-9_]+|[A-Za-z_$][\w$]*(?=\(\)))(\(\))?$/;
const IDENTIFIER_SOURCE_EXTENSIONS =
  /\.(ts|mts|js|mjs|cjs|svelte|kt|kts|java|swift|m|h|gradle|yml|yaml|json|css|html|sh|py|rb|toml)$/;
const WORD = /[A-Za-z_$][\w$]*/g;


import { readFileSync, writeFileSync } from 'node:fs';
import { format, resolveConfig } from 'prettier';
import { iconTokenEntries } from '../../web/src/lib/design/iconTokens.ts';
import { themes } from '../../web/src/lib/design/tokens.ts';
import { ROOT, isMain } from '../lib/proc.mjs';

const SOURCE = `${ROOT}/web/src/lib/icons/`;
export const NATIVE_ICONS_TARGET = `${ROOT}/experiments/native-architecture/src/rsdDrawing/icons.generated.ts`;

// The drawing toolbar's icons, by shipping icon name; a deferred icon names its subdirectory.
export const NATIVE_ICON_SOURCES = {
  undo: 'undo.svg',
  'brush-pen': 'brush-pen.svg',
  'brush-crayon': 'brush-crayon.svg',
  'brush-magic': 'brush-magic.svg',
  'brush-eraser': 'brush-eraser.svg',
  'trash-closed': 'trash-closed.svg',
  settings: 'settings.svg',
  camera: 'camera.svg',
  shapes: 'shapes.svg',
  'wand-stars': 'wand-stars.svg',
  'more-colors': 'more-colors.svg',
  'parent-center': 'deferred/parent-center.svg',
  controls: 'deferred/controls.svg',
};

const THEMES = ['light', 'dark'];
const ICON_TOKEN_FILL = /style="fill:var\((--icon-[a-z0-9-]+),(#[0-9a-f]{3,8})\)"/g;
// Monochrome glyphs bake the light icon ink on their root; the web re-inks them with --icon-ink.
const MONOCHROME_ROOT_FILL = `<svg xmlns="http://www.w3.org/2000/svg" fill="${themes.light.iconInk}"`;
const CURRENT_COLOR_ROOT = '<svg xmlns="http://www.w3.org/2000/svg" fill="currentColor"';

function themedIcon(name, svg, theme) {
  const parts = new Map(iconTokenEntries().map((entry) => [entry.cssVar, entry]));
  const themed = svg
    .replace(ICON_TOKEN_FILL, (_, cssVar, fallback) => {
      const part = parts.get(cssVar);
      if (!part || part.light !== fallback)
        throw new Error(`Unresolved icon token ${cssVar} in ${name}`);
      return `fill="${part[theme]}"`;
    })
    .replace(MONOCHROME_ROOT_FILL, CURRENT_COLOR_ROOT);
  if (/var\(|style=|<style|class=/.test(themed))
    throw new Error(`Unsupported styling in native icon ${name}`);
  return themed;
}

function constName(name, suffix = '') {
  return `${name.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase())}${suffix}`;
}

export function nativeIconSource(sources = NATIVE_ICON_SOURCES) {
  const declarations = [];
  const entries = [];
  for (const [name, file] of Object.entries(sources)) {
    const svg = readFileSync(`${SOURCE}${file}`, 'utf8').trim();
    const [light, dark] = THEMES.map((theme) => themedIcon(name, svg, theme));
    if (light === dark) {
      declarations.push(`const ${constName(name)} = ${JSON.stringify(light)};`);
      entries.push(`'${name}': { light: ${constName(name)}, dark: ${constName(name)} },`);
    } else {
      declarations.push(`const ${constName(name, 'Light')} = ${JSON.stringify(light)};`);
      declarations.push(`const ${constName(name, 'Dark')} = ${JSON.stringify(dark)};`);
      entries.push(
        `'${name}': { light: ${constName(name, 'Light')}, dark: ${constName(name, 'Dark')} },`
      );
    }
  }
  return [
    '// Generated by tools/migration/gen-native-icons.mjs from web/src/lib/icons; do not edit.',
    '',
    ...declarations,
    '',
    `export const NATIVE_ICONS = {\n${entries.join('\n')}\n} as const satisfies Record<string, Record<'light' | 'dark', string>>;`,
    '',
    'export type NativeIconName = keyof typeof NATIVE_ICONS;',
    '',
  ].join('\n');
}

export async function generateNativeIcons(argv) {
  if (argv.some((arg) => arg !== '--check')) throw new Error('Only --check is supported.');
  const content = await format(nativeIconSource(), {
    ...(await resolveConfig(NATIVE_ICONS_TARGET)),
    filepath: NATIVE_ICONS_TARGET,
  });
  if (!argv.includes('--check')) writeFileSync(NATIVE_ICONS_TARGET, content);
  else if (readFileSync(NATIVE_ICONS_TARGET, 'utf8') !== content)
    throw new Error('Native icon drift: icons.generated.ts');
  return { icons: Object.keys(NATIVE_ICON_SOURCES).length };
}

if (isMain(import.meta.url))
  console.log(JSON.stringify(await generateNativeIcons(process.argv.slice(2))));

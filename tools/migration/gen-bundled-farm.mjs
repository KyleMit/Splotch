import { readFileSync, writeFileSync } from 'node:fs';
import { basename, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isMain } from '../lib/proc.mjs';
import { FARM_PAGE_IDS } from '../../experiments/native-architecture/src/drawing/bundledBooks.ts';
import { parseOverlay } from '../../experiments/native-architecture/src/drawing/overlayOutline.ts';

const root = fileURLToPath(new URL('../../', import.meta.url));
export const BUNDLED_FARM_DIR = `${root}experiments/native-architecture/src/drawing/bundledFarm/`;
const SOURCE_DIR = `${root}web/static/coloring/farm/`;
// Both targets import the shipped files as Metro assets: the native apps carry them as files in
// the app package (Android resources, iOS bundle files), so no image rides in the JavaScript
// bundle; the web export serves them hashed, off the startup script.
export const NATIVE_IMAGES_FILE = 'images.ts';
export const WEB_IMAGES_FILE = 'images.web.ts';
// The picker's covers and page thumbnails ship in their own module, which only the picker's lazy
// chunk imports, so their asset entries stay off the web startup path the paper's fills are on.
export const NATIVE_PICKER_IMAGES_FILE = 'pickerImages.ts';
export const WEB_PICKER_IMAGES_FILE = 'pickerImages.web.ts';
// The native apps read each page's line art from the shipped overlay SVGs on first use
// (bundledOutlines.ts); the web export imports the page modules generated from the same files.
export const NATIVE_OUTLINE_FILES_FILE = 'outlineFiles.ts';
// Resolved from the generated modules in bundledFarm/, not from this script.
const GENERATED_ART_TYPES_SPECIFIER = '../bundledBookAssets';
const ASSET_URI_HELPERS = {
  native: { name: 'nativeAssetUri', specifier: '../../platform/nativeAsset' },
  web: { name: 'webAssetUri', specifier: '../../platform/webAsset' },
};
const GENERATED_HEADER =
  '// Generated by tools/migration/gen-bundled-farm.mjs from web/static/coloring.';
const ORIENTATION_SLUGS = { landscape: 'wide', portrait: 'tall' };
const THEMES = {
  light: {
    overlay: 'overlay.svg',
    fill: 'light.webp',
    selector: 'selector.webp',
    cover: 'cover.thumb.webp',
  },
  dark: {
    overlay: 'dark.overlay.svg',
    fill: 'night.webp',
    selector: 'dark.selector.webp',
    cover: 'cover.chalk.thumb.webp',
  },
};
const ASSET_PLACEHOLDER = /"@asset:([^"]+)"/g;

const slugOf = (pageId) => pageId.split('/')[1];
const themed = (build) =>
  Object.fromEntries(Object.keys(THEMES).map((theme) => [theme, build(theme)]));
const oriented = (build) =>
  Object.fromEntries(
    Object.entries(ORIENTATION_SLUGS).map(([orientation, slug]) => [
      orientation,
      themed((theme) => build(slug, theme, orientation)),
    ])
  );

const pageOutlineFiles = (slug) =>
  oriented(
    (orientationSlug, theme) => `${SOURCE_DIR}${slug}-${orientationSlug}.${THEMES[theme].overlay}`
  );

export function bundledPageOutlines(slug) {
  const files = pageOutlineFiles(slug);
  return oriented((_, theme, orientation) => {
    const path = files[orientation][theme];
    return parseOverlay(readFileSync(path, 'utf8'), basename(path));
  });
}

// Every page's overlay SVGs as absolute paths, in the shape of the native outline files module.
export function bundledFarmOutlineFiles() {
  return Object.fromEntries(
    FARM_PAGE_IDS.map((pageId) => [pageId, pageOutlineFiles(slugOf(pageId))])
  );
}

// Every bundled image as the absolute path of the shipping file it carries, in the shape of the
// generated images modules: the paper's fills, and the picker's page thumbnails and covers.
export function bundledFarmImageFiles() {
  const perPage = (build) =>
    Object.fromEntries(FARM_PAGE_IDS.map((pageId) => [pageId, build(slugOf(pageId))]));
  return {
    pages: perPage((slug) =>
      oriented(
        (orientationSlug, theme) => `${SOURCE_DIR}${slug}-${orientationSlug}.${THEMES[theme].fill}`
      )
    ),
    // The picker shows the thumbnails cut to the paper's own orientation, as shipping does.
    selectors: perPage((slug) =>
      oriented(
        (orientationSlug, theme) =>
          `${SOURCE_DIR}${slug}-${orientationSlug}.${THEMES[theme].selector}`
      )
    ),
    covers: themed((theme) => `${SOURCE_DIR}${THEMES[theme].cover}`),
  };
}

// Every file path in a bundledFarmImageFiles() or bundledFarmOutlineFiles() entry, however deeply
// its slots nest.
export function imageFilePaths(files) {
  return typeof files === 'string' ? [files] : Object.values(files).flatMap(imageFilePaths);
}

function outlineModuleSource(slug) {
  return [
    GENERATED_HEADER,
    `import type { BundledPageOutlines } from '${GENERATED_ART_TYPES_SPECIFIER}';`,
    '',
    `export const ${slug}Outlines = ${JSON.stringify(bundledPageOutlines(slug), null, 2)} satisfies BundledPageOutlines;`,
    '',
  ].join('\n');
}

function assetsBody(files, value) {
  const placeholders = JSON.stringify(
    files,
    (_, file) => (typeof file === 'string' ? `@asset:${file}` : file),
    2
  );
  return placeholders.replace(ASSET_PLACEHOLDER, (_, path) => value(path));
}

const ASSET_MODULES = {
  fills: {
    types: ['BundledBookImages'],
    exports: () => [['BUNDLED_FARM_IMAGES', bundledFarmImageFiles().pages, 'BundledBookImages']],
  },
  picker: {
    types: ['BundledBookImages', 'BundledThemeImages'],
    exports: () => {
      const { selectors, covers } = bundledFarmImageFiles();
      return [
        ['BUNDLED_FARM_SELECTORS', selectors, 'BundledBookImages'],
        ['BUNDLED_FARM_COVERS', covers, 'BundledThemeImages'],
      ];
    },
  },
  outlines: {
    types: ['BundledBookOutlineFiles'],
    exports: () => [
      ['BUNDLED_FARM_OUTLINE_FILES', bundledFarmOutlineFiles(), 'BundledBookOutlineFiles'],
    ],
  },
};

function assetIdentifier(path) {
  return basename(path)
    .replace(/\.[a-z]+$/, '')
    .split(/[-.]/)
    .map((part, index) => (index === 0 ? part : part[0].toUpperCase() + part.slice(1)))
    .join('');
}

// Each shipped file is a Metro asset import. An images module passes it through its target's
// URI helper; the outline files module exports the native asset ids themselves.
function assetModuleSource(module, helper) {
  const exports = ASSET_MODULES[module].exports();
  const paths = exports.flatMap(([, files]) => imageFilePaths(files));
  const value = helper ? (path) => `${helper.name}(${assetIdentifier(path)})` : assetIdentifier;
  return [
    GENERATED_HEADER,
    ...(helper ? [`import { ${helper.name} } from '${helper.specifier}';`] : []),
    `import type { ${ASSET_MODULES[module].types.join(', ')} } from '${GENERATED_ART_TYPES_SPECIFIER}';`,
    ...paths.map(
      (path) =>
        `import ${assetIdentifier(path)} from '${relative(BUNDLED_FARM_DIR, path).split('\\').join('/')}';`
    ),
    '',
    ...exports.flatMap(([name, files, type]) => [
      `export const ${name} = ${assetsBody(files, value)} satisfies ${type};`,
      '',
    ]),
  ].join('\n');
}

function generatedModules() {
  return [
    ...FARM_PAGE_IDS.map(slugOf).map((slug) => [`${slug}.ts`, () => outlineModuleSource(slug)]),
    [NATIVE_IMAGES_FILE, () => assetModuleSource('fills', ASSET_URI_HELPERS.native)],
    [WEB_IMAGES_FILE, () => assetModuleSource('fills', ASSET_URI_HELPERS.web)],
    [NATIVE_PICKER_IMAGES_FILE, () => assetModuleSource('picker', ASSET_URI_HELPERS.native)],
    [WEB_PICKER_IMAGES_FILE, () => assetModuleSource('picker', ASSET_URI_HELPERS.web)],
    [NATIVE_OUTLINE_FILES_FILE, () => assetModuleSource('outlines')],
  ];
}

export async function generateBundledFarm(argv) {
  if (argv.some((arg) => arg !== '--check')) throw new Error('Only --check is supported.');
  // The deploy's precache check reads this module's file lists from a production install, which
  // has no Prettier; only regenerating the modules formats them.
  const { format, resolveConfig } = await import('prettier');
  const modules = generatedModules();
  for (const [file, source] of modules) {
    const path = `${BUNDLED_FARM_DIR}${file}`;
    const content = await format(source(), { ...(await resolveConfig(path)), filepath: path });
    if (argv.includes('--check')) {
      if (readFileSync(path, 'utf8') !== content)
        throw new Error(`Bundled Farm art drift: ${file}`);
    } else writeFileSync(path, content);
  }
  return { pages: FARM_PAGE_IDS.length, modules: modules.length };
}

if (isMain(import.meta.url))
  console.log(JSON.stringify(await generateBundledFarm(process.argv.slice(2))));

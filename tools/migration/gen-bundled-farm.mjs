import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import { isMain } from '../lib/proc.mjs';
import { FARM_PAGE_IDS } from '../../experiments/native-architecture/src/drawing/bundledBooks.ts';

const root = fileURLToPath(new URL('../../', import.meta.url));
export const BUNDLED_FARM_DIR = `${root}experiments/native-architecture/src/drawing/bundledFarm/`;
const SOURCE_DIR = `${root}web/static/coloring/farm/`;
// Both orientations' Magic fills come from the compact pack's screen-sized tier (ADR-0103):
// the canonical full-size pair of fills does not fit the native web precache budget
// (MAX_NATIVE_WEB_PRECACHE_BYTES) beside the tall line art.
export const BUNDLED_FARM_FILL_DIR = `${root}web/static/coloring/max-1152px/farm/`;
// Resolved from the generated module in bundledFarm/, not from this script.
const GENERATED_ART_TYPES_SPECIFIER = '../bundledBookAssets';
const ORIENTATION_SLUGS = { landscape: 'wide', portrait: 'tall' };
const THEMES = {
  light: { overlay: 'overlay.svg', fill: 'light.webp', selector: 'selector.webp' },
  dark: { overlay: 'dark.overlay.svg', fill: 'night.webp', selector: 'dark.selector.webp' },
};
const OUTLINE_ATTRIBUTES = {
  path: ['d'],
  ellipse: ['rx', 'ry', 'transform'],
  rect: ['width', 'height', 'x', 'y', 'rx', 'ry', 'transform'],
  circle: ['cx', 'cy', 'r'],
};
const ROOT_ATTRIBUTES = ['xmlns', 'width', 'height', 'fill', 'viewBox'];
const SVG_DOCUMENT = /^<svg ([^>]*)>(.*)<\/svg>\s*$/s;
const ELEMENT = /<([a-z]+)((?: [a-zA-Z]+="[^"]*")*)\/>/gy;
const ATTRIBUTE = / ([a-zA-Z]+)="([^"]*)"/g;

function attributes(source, allowed, context) {
  const entries = [...source.matchAll(ATTRIBUTE)].map(([, name, value]) => [name, value]);
  const unknown = entries.filter(([name]) => !allowed.includes(name));
  if (unknown.length)
    throw new Error(`Unsupported ${context} attributes: ${unknown.map(([name]) => name)}`);
  return Object.fromEntries(entries);
}

// The canonical overlays are flat SVGO output: one root and self-closing shape children.
export function parseOverlay(svg, name) {
  const document = SVG_DOCUMENT.exec(svg);
  if (!document) throw new Error(`Unexpected SVG document in ${name}`);
  const rootAttributes = attributes(` ${document[1]}`, ROOT_ATTRIBUTES, `${name} root`);
  const body = document[2];
  const outline = [];
  for (let offset = 0; offset < body.length; offset = ELEMENT.lastIndex) {
    ELEMENT.lastIndex = offset;
    const match = ELEMENT.exec(body);
    if (!match) throw new Error(`Unexpected SVG content in ${name}`);
    const [, kind, source] = match;
    if (!Object.hasOwn(OUTLINE_ATTRIBUTES, kind))
      throw new Error(`Unsupported ${kind} element in ${name}`);
    outline.push({ kind, ...attributes(source, OUTLINE_ATTRIBUTES[kind], `${name} ${kind}`) });
  }
  if (outline.length === 0) throw new Error(`Empty SVG outline in ${name}`);
  return {
    viewBox: rootAttributes.viewBox,
    ink: rootAttributes.fill ?? '#000',
    outline,
  };
}

function webpUri(path) {
  return `data:image/webp;base64,${readFileSync(path).toString('base64')}`;
}

export function bundledPageArt(slug) {
  const variant = (orientation, theme) => {
    const basename = `${slug}-${ORIENTATION_SLUGS[orientation]}`;
    const name = `${basename}.${THEMES[theme].overlay}`;
    return {
      ...parseOverlay(readFileSync(`${SOURCE_DIR}${name}`, 'utf8'), name),
      fill: webpUri(`${BUNDLED_FARM_FILL_DIR}${basename}.${THEMES[theme].fill}`),
    };
  };
  const themed = (build) =>
    Object.fromEntries(Object.keys(THEMES).map((theme) => [theme, build(theme)]));
  return {
    ...Object.fromEntries(
      Object.keys(ORIENTATION_SLUGS).map((orientation) => [
        orientation,
        themed((theme) => variant(orientation, theme)),
      ])
    ),
    // The picker keeps the wide thumbnails on every paper.
    selector: themed((theme) => webpUri(`${SOURCE_DIR}${slug}-wide.${THEMES[theme].selector}`)),
  };
}

function moduleSource(slug) {
  return [
    '// Generated by tools/migration/gen-bundled-farm.mjs from web/static/coloring.',
    `import type { BundledPageArt } from '${GENERATED_ART_TYPES_SPECIFIER}';`,
    '',
    `export const ${slug}Art = ${JSON.stringify(bundledPageArt(slug), null, 2)} satisfies BundledPageArt;`,
    '',
  ].join('\n');
}

export async function generateBundledFarm(argv) {
  if (argv.some((arg) => arg !== '--check')) throw new Error('Only --check is supported.');
  const slugs = FARM_PAGE_IDS.map((pageId) => pageId.split('/')[1]);
  for (const slug of slugs) {
    const path = `${BUNDLED_FARM_DIR}${slug}.ts`;
    const content = await format(moduleSource(slug), {
      ...(await resolveConfig(path)),
      filepath: path,
    });
    if (argv.includes('--check')) {
      if (readFileSync(path, 'utf8') !== content)
        throw new Error(`Bundled Farm art drift: ${slug}.ts`);
    } else writeFileSync(path, content);
  }
  return { pages: slugs.length };
}

if (isMain(import.meta.url))
  console.log(JSON.stringify(await generateBundledFarm(process.argv.slice(2))));

import { readFileSync, writeFileSync } from 'node:fs';
import { basename, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import { isMain } from '../lib/proc.mjs';
import { FARM_PAGE_IDS } from '../../experiments/native-architecture/src/drawing/bundledBooks.ts';

const root = fileURLToPath(new URL('../../', import.meta.url));
export const BUNDLED_FARM_DIR = `${root}experiments/native-architecture/src/drawing/bundledFarm/`;
const SOURCE_DIR = `${root}web/static/coloring/farm/`;
// Both orientations' Magic fills come from the compact pack's screen-sized tier (ADR-0103):
// the canonical full-size pair of fills does not fit the native web precache budget
// (MAX_NATIVE_WEB_PRECACHE_BYTES) beside the tall line art.
export const BUNDLED_FARM_FILL_DIR = `${root}web/static/coloring/max-1152px/farm/`;
// The native apps decode every bundled image from these data URIs, offline and without an asset
// lookup; the web export resolves the same files as hashed Metro assets instead, so they stay out
// of the startup script (images.web.ts).
export const NATIVE_IMAGES_FILE = 'images.ts';
export const WEB_IMAGES_FILE = 'images.web.ts';
// Resolved from the generated modules in bundledFarm/, not from this script.
const GENERATED_ART_TYPES_SPECIFIER = '../bundledBookAssets';
const GENERATED_HEADER =
  '// Generated by tools/migration/gen-bundled-farm.mjs from web/static/coloring.';
const ORIENTATION_SLUGS = { landscape: 'wide', portrait: 'tall' };
const THEMES = {
  light: {
    overlay: 'overlay.svg',
    fill: 'light.webp',
    selector: 'selector.webp',
    cover: 'cover.thumb.webp',
  },
  dark: {
    overlay: 'dark.overlay.svg',
    fill: 'night.webp',
    selector: 'dark.selector.webp',
    cover: 'cover.chalk.thumb.webp',
  },
};
const OUTLINE_ATTRIBUTES = {
  path: ['d'],
  ellipse: ['rx', 'ry', 'transform'],
  rect: ['width', 'height', 'x', 'y', 'rx', 'ry', 'transform'],
  circle: ['cx', 'cy', 'r'],
};
const ROOT_ATTRIBUTES = ['xmlns', 'width', 'height', 'fill', 'viewBox'];
const SVG_DOCUMENT = /^<svg ([^>]*)>(.*)<\/svg>\s*$/s;
const ELEMENT = /<([a-z]+)((?: [a-zA-Z]+="[^"]*")*)\/>/gy;
const ATTRIBUTE = / ([a-zA-Z]+)="([^"]*)"/g;
const IMAGE_PLACEHOLDER = /"@image:([^"]+)"/g;

function attributes(source, allowed, context) {
  const entries = [...source.matchAll(ATTRIBUTE)].map(([, name, value]) => [name, value]);
  const unknown = entries.filter(([name]) => !allowed.includes(name));
  if (unknown.length)
    throw new Error(`Unsupported ${context} attributes: ${unknown.map(([name]) => name)}`);
  return Object.fromEntries(entries);
}

// The canonical overlays are flat SVGO output: one root and self-closing shape children.
export function parseOverlay(svg, name) {
  const document = SVG_DOCUMENT.exec(svg);
  if (!document) throw new Error(`Unexpected SVG document in ${name}`);
  const rootAttributes = attributes(` ${document[1]}`, ROOT_ATTRIBUTES, `${name} root`);
  const body = document[2];
  const outline = [];
  for (let offset = 0; offset < body.length; offset = ELEMENT.lastIndex) {
    ELEMENT.lastIndex = offset;
    const match = ELEMENT.exec(body);
    if (!match) throw new Error(`Unexpected SVG content in ${name}`);
    const [, kind, source] = match;
    if (!Object.hasOwn(OUTLINE_ATTRIBUTES, kind))
      throw new Error(`Unsupported ${kind} element in ${name}`);
    outline.push({ kind, ...attributes(source, OUTLINE_ATTRIBUTES[kind], `${name} ${kind}`) });
  }
  if (outline.length === 0) throw new Error(`Empty SVG outline in ${name}`);
  return {
    viewBox: rootAttributes.viewBox,
    ink: rootAttributes.fill ?? '#000',
    outline,
  };
}

const slugOf = (pageId) => pageId.split('/')[1];
const themed = (build) =>
  Object.fromEntries(Object.keys(THEMES).map((theme) => [theme, build(theme)]));
const oriented = (build) =>
  Object.fromEntries(
    Object.entries(ORIENTATION_SLUGS).map(([orientation, slug]) => [
      orientation,
      themed((theme) => build(slug, theme)),
    ])
  );

export function bundledPageOutlines(slug) {
  return oriented((orientationSlug, theme) => {
    const name = `${slug}-${orientationSlug}.${THEMES[theme].overlay}`;
    return parseOverlay(readFileSync(`${SOURCE_DIR}${name}`, 'utf8'), name);
  });
}

// Every bundled image as the absolute path of the shipping file it carries, in the shape of the
// generated images modules.
export function bundledFarmImageFiles() {
  return {
    pages: Object.fromEntries(
      FARM_PAGE_IDS.map((pageId) => {
        const slug = slugOf(pageId);
        return [
          pageId,
          {
            ...oriented(
              (orientationSlug, theme) =>
                `${BUNDLED_FARM_FILL_DIR}${slug}-${orientationSlug}.${THEMES[theme].fill}`
            ),
            // The picker keeps the wide thumbnails on every paper.
            selector: themed((theme) => `${SOURCE_DIR}${slug}-wide.${THEMES[theme].selector}`),
          },
        ];
      })
    ),
    covers: themed((theme) => `${SOURCE_DIR}${THEMES[theme].cover}`),
  };
}

function outlineModuleSource(slug) {
  return [
    GENERATED_HEADER,
    `import type { BundledPageOutlines } from '${GENERATED_ART_TYPES_SPECIFIER}';`,
    '',
    `export const ${slug}Outlines = ${JSON.stringify(bundledPageOutlines(slug), null, 2)} satisfies BundledPageOutlines;`,
    '',
  ].join('\n');
}

function imagesBody(files, image) {
  const placeholders = JSON.stringify(
    files,
    (_, value) => (typeof value === 'string' ? `@image:${value}` : value),
    2
  );
  return placeholders.replace(IMAGE_PLACEHOLDER, (_, path) => image(path));
}

function imagesExports(body) {
  const { pages, covers } = bundledFarmImageFiles();
  return [
    `export const BUNDLED_FARM_IMAGES = ${body(pages)} satisfies BundledBookImages;`,
    '',
    `export const BUNDLED_FARM_COVERS = ${body(covers)} satisfies BundledThemeImages;`,
    '',
  ];
}

const IMAGE_TYPES_IMPORT = `import type { BundledBookImages, BundledThemeImages } from '${GENERATED_ART_TYPES_SPECIFIER}';`;

function nativeImagesSource() {
  const dataUri = (path) =>
    JSON.stringify(`data:image/webp;base64,${readFileSync(path).toString('base64')}`);
  return [
    GENERATED_HEADER,
    IMAGE_TYPES_IMPORT,
    '',
    ...imagesExports((files) => imagesBody(files, dataUri)),
  ].join('\n');
}

export function webImageIdentifier(path) {
  return basename(path, '.webp')
    .split(/[-.]/)
    .map((part, index) => (index === 0 ? part : part[0].toUpperCase() + part.slice(1)))
    .join('');
}

function webImagesSource() {
  const { pages, covers } = bundledFarmImageFiles();
  const paths = [
    ...Object.values(pages).flatMap((page) =>
      Object.values(page).flatMap((variants) => Object.values(variants))
    ),
    ...Object.values(covers),
  ];
  return [
    GENERATED_HEADER,
    "import { Asset } from 'expo-asset';",
    IMAGE_TYPES_IMPORT,
    ...paths.map(
      (path) =>
        `import ${webImageIdentifier(path)} from '${relative(BUNDLED_FARM_DIR, path).split('\\').join('/')}';`
    ),
    '',
    'const uri = (source: Parameters<typeof Asset.fromModule>[0]) => Asset.fromModule(source).uri;',
    '',
    ...imagesExports((files) => imagesBody(files, (path) => `uri(${webImageIdentifier(path)})`)),
  ].join('\n');
}

function generatedModules() {
  return [
    ...FARM_PAGE_IDS.map(slugOf).map((slug) => [`${slug}.ts`, () => outlineModuleSource(slug)]),
    [NATIVE_IMAGES_FILE, nativeImagesSource],
    [WEB_IMAGES_FILE, webImagesSource],
  ];
}

export async function generateBundledFarm(argv) {
  if (argv.some((arg) => arg !== '--check')) throw new Error('Only --check is supported.');
  const modules = generatedModules();
  for (const [file, source] of modules) {
    const path = `${BUNDLED_FARM_DIR}${file}`;
    const content = await format(source(), { ...(await resolveConfig(path)), filepath: path });
    if (argv.includes('--check')) {
      if (readFileSync(path, 'utf8') !== content)
        throw new Error(`Bundled Farm art drift: ${file}`);
    } else writeFileSync(path, content);
  }
  return { pages: FARM_PAGE_IDS.length, modules: modules.length };
}

if (isMain(import.meta.url))
  console.log(JSON.stringify(await generateBundledFarm(process.argv.slice(2))));

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createBookCatalog } from '../../src/lib/state/bookCatalog.ts';
import { format, resolveConfig } from 'prettier';
import { isMain } from '../lib/proc.mjs';

const root = fileURLToPath(new URL('../../', import.meta.url));
const target = `${root}src/offlineLibrary/`;
const variants = ['compact', 'full'];
const suffixes = [
  'light.webp',
  'night.webp',
  'overlay.svg',
  'dark.overlay.svg',
  'selector.webp',
  'dark.selector.webp',
];
const hash = (value) => createHash('sha256').update(value).digest('hex');

export async function generateOfflineCatalog(argv) {
  if (argv.some((arg) => arg !== '--check')) throw new Error('Only --check is supported.');
  const books = createBookCatalog((id, label, _platforms, pages) => ({
    id,
    label,
    pages: pages((slug, name) => ({ slug, label: name })),
  })).filter(({ id }) => id !== 'farm');
  const catalog = books.map((book) => ({
    id: book.id,
    variants: Object.fromEntries(
      variants.map((variant) => {
        const paths = [
          `/coloring/${book.id}/cover.thumb.webp`,
          `/coloring/${book.id}/cover.chalk.thumb.webp`,
          ...book.pages.flatMap(({ slug }) =>
            ['tall', 'wide'].flatMap((orientation) =>
              suffixes.map((suffix) => `/coloring/${book.id}/${slug}-${orientation}.${suffix}`)
            )
          ),
        ];
        const files = paths.map((path) => {
          const downloadPath =
            variant === 'compact' && /\.(light|night)\.webp$/.test(path)
              ? path.replace('/coloring/', '/coloring/max-1152px/')
              : path;
          const bytes = readFileSync(`${root}assets/static${downloadPath}`);
          return { path, downloadPath, bytes: bytes.length, sha256: hash(bytes) };
        });
        return [
          variant,
          {
            revision: hash(JSON.stringify(files)),
            bytes: files.reduce((sum, file) => sum + file.bytes, 0),
            files,
          },
        ];
      })
    ),
  }));
  const outputs = {
    'catalog.generated.json': `${JSON.stringify({ formatVersion: 1, books: catalog }, null, 2)}\n`,
    'books.generated.ts': `// Generated by tools/migration/gen-offline-catalog.mjs.\nexport const OFFLINE_BOOKS = ${JSON.stringify(books, null, 2)} as const;\n`,
  };
  for (const [name, rawContent] of Object.entries(outputs)) {
    const content = await format(rawContent, {
      ...(await resolveConfig(`${target}${name}`)),
      filepath: name,
    });
    if (argv.includes('--check')) {
      if (readFileSync(`${target}${name}`, 'utf8') !== content)
        throw new Error(`Offline catalog drift: ${name}`);
    } else writeFileSync(`${target}${name}`, content);
  }
  return {
    books: books.length,
    filesPerVariant: catalog.map((book) => book.variants.full.files.length),
  };
}
if (isMain(import.meta.url))
  console.log(JSON.stringify(await generateOfflineCatalog(process.argv.slice(2))));
